# The evidence summary for the report, as HTML or as plain lines: selective disappearance, and selective appearance
# when anything was saved for it. Built from the same graders as the app.
evidence_report_grades <- function(entries, trait) {
  g <- tryCatch(grade_evidence(entries, trait = trait), error = function(e) NULL)
  ga <- tryCatch(grade_appearance(entries, trait = trait), error = function(e) NULL)
  Filter(Negate(is.null), list(`Selective disappearance` = g, `Selective appearance` = ga))
}
footnote_of <- function(lines, i) {
  fn <- if ("Footnote" %in% names(lines)) lines$Footnote[[i]] else ""
  if (length(fn) && !is.na(fn) && nzchar(fn)) fn else ""
}
evidence_report_html <- function(entries, trait) {
  gs <- evidence_report_grades(entries, trait)
  if (!length(gs)) return(character(0))
  mark <- c(supports = "&#10003;", caveat = "!", contradicts = "&#10007;", `not saved` = "&ndash;")
  out <- "<h2>Evidence summary</h2>"
  for (nm in names(gs)) {
    g <- gs[[nm]]
    out <- c(out, paste0("<h3>", html_escape(nm), "</h3>"), paste0("<p><strong>", html_escape(g$headline), "</strong></p>"))
    if (!is.null(g$finding)) out <- c(out, paste0("<p><strong>Finding:</strong> the saved evidence suggests that ", html_escape(g$finding), ".</p>"))
    if (!is.null(g$explanation)) out <- c(out, paste0("<p>", html_escape(g$explanation), "</p>"))
    if (is.data.frame(g$lines) && nrow(g$lines)) {
      rows <- vapply(seq_len(nrow(g$lines)), function(i) {
        fn <- footnote_of(g$lines, i)
        paste0("<tr><td>", mark[[g$lines$Status[[i]]]], "</td><td><b>", html_escape(g$lines$Evidence[[i]]), "</b></td><td>",
               html_escape(g$lines$Note[[i]]), if (nzchar(fn)) paste0("<br><small>", html_escape(fn), "</small>") else "", "</td></tr>")
      }, character(1))
      out <- c(out, "<table>", rows, "</table>")
    }
    if (length(g$cautions)) out <- c(out, "<ul>", paste0("<li>", html_escape(g$cautions), "</li>"), "</ul>")
    if (length(g$pending)) out <- c(out, "<p><strong>Complete the following checks for more robust evidence:</strong></p><ol>",
                                    paste0("<li>", html_escape(unname(PENDING_TEXT[g$pending])), "</li>"), "</ol>")
  }
  out
}
evidence_report_text <- function(entries, trait) {
  gs <- evidence_report_grades(entries, trait)
  if (!length(gs)) return(character(0))
  mark <- c(supports = "[+]", caveat = "[!]", contradicts = "[x]", `not saved` = "[ ]")
  out <- "EVIDENCE SUMMARY"
  for (nm in names(gs)) {
    g <- gs[[nm]]
    out <- c(out, toupper(nm), g$headline)
    if (!is.null(g$finding)) out <- c(out, paste0("Finding: the saved evidence suggests that ", g$finding, "."))
    if (!is.null(g$explanation)) out <- c(out, g$explanation)
    if (is.data.frame(g$lines) && nrow(g$lines)) {
      out <- c(out, vapply(seq_len(nrow(g$lines)), function(i) {
        fn <- footnote_of(g$lines, i)
        paste(mark[[g$lines$Status[[i]]]], g$lines$Evidence[[i]], "-", g$lines$Note[[i]], if (nzchar(fn)) paste0("[", fn, "]") else "")
      }, character(1)))
    }
    if (length(g$cautions)) out <- c(out, paste("Note:", g$cautions))
    if (length(g$pending)) out <- c(out, "Complete the following checks for more robust evidence:",
                                    paste0(seq_along(g$pending), ". ", unname(PENDING_TEXT[g$pending])))
    out <- c(out, "")
  }
  out
}

# Saved results in the order they appear in the app (step, then top to bottom, left to right), and the data they
# were computed on, stated once rather than repeated under every result.
report_order <- function(entries) {
  if (!length(entries)) return(entries)
  ord <- vapply(entries, function(e) as.numeric(if (is.null(e$order)) 9999 else e$order), numeric(1))
  entries[order(ord, seq_along(entries))]
}
report_data_line <- function(entries) {
  d <- unique(vapply(entries, function(e) if (is.null(e$data)) "" else e$data, character(1)))
  d <- d[nzchar(d)]
  if (!length(d)) return(NULL)
  if (length(d) == 1) paste("Data analysed:", d) else paste("Data analysed (results were saved from more than one dataset):", paste(d, collapse = " | "))
}

text_report <- function(entries, heading = "disappR report", trait = "the trait") {
  lines <- c(heading, paste("Generated:", format(Sys.time())), "")
  if (!length(entries)) lines <- c(lines, "No results were saved.")
  entries <- report_order(entries)
  dl <- report_data_line(entries)
  if (!is.null(dl)) lines <- c(lines, dl, "")
  if (length(entries)) lines <- c(lines, evidence_report_text(entries, trait))
  for (e in entries) {
    lines <- c(lines, paste0("== ", e$section, " \u00b7 ", e$title, " =="))
    if (length(e$text)) lines <- c(lines, paste("-", e$text))
    tabs <- e$tables
    for (j in seq_along(tabs)) {
      cap <- names(tabs)[j]
      if (!is.null(cap) && !is.na(cap) && nzchar(cap)) lines <- c(lines, paste0("[", cap, "]"))
      lines <- c(lines, utils::capture.output(print(as.data.frame(tabs[[j]]), row.names = FALSE)))
    }
    if (length(e$plots)) lines <- c(lines, sprintf("(%d plot(s) included in the HTML report)", length(e$plots)))
    if (!is.null(e$code)) lines <- c(lines, e$code)
    lines <- c(lines, "")
  }
  lines
}

