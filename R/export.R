    paras <- c(paras, paste0("We compared the AIC advantage of ", bb$model %||% "the lifespan-proxy model", " over Model 1 with a parametric bootstrap: ", n(bb$n),
                             " datasets were simulated from a model without any lifespan-proxy term (", tolower(bb$null_function %||% "a flexible"),
                             " ageing function, individual random intercepts and slopes, and ",
                             if (identical(bb$disp %||% "constant", "constant")) "a constant residual variance" else "the residual variance changing with age as in the analysis",
                             "), keeping every individual's observed ages, ALR and AFR, and the advantage was recomputed in each."))
  }
  sw <- first_with("software")
  if (!is.null(sw)) {
    sw <- sw[!is.na(sw)]
    rv <- if ("R" %in% names(sw)) sw[["R"]] else ""
    pk <- sw[names(sw) != "R"]
    paras <- c(paras, paste0("Analyses were run in R ", rv, if (length(pk)) paste0(" with ", paste(paste(names(pk), pk), collapse = ", ")) else "", "."))
  }

  # ---- conflicts between the selected results
  lab <- function(e) paste0("'", e$title %||% "", "'")
  data_lab <- vapply(entries, function(e) e$data %||% "", character(1))
  if (length(unique(data_lab[nzchar(data_lab)])) > 1)
    conflicts <- c(conflicts, paste0("Different data or data settings (", and_list(unique(data_lab[nzchar(data_lab)])), "): the data paragraph describes the first."))
  steps <- vapply(mc, function(x) { s <- x$data$step; if (is.numeric(s) && length(s) == 1 && is.finite(s)) format_num(s) else "" }, character(1))
  if (length(unique(steps[nzchar(steps)])) > 1)
    conflicts <- c(conflicts, paste0("Different sampling intervals (", and_list(unique(steps[nzchar(steps)])), ")."))
  if (length(model_entries) > 1) {
    fields <- c(family = "error family", age_function = "ageing function", random = "random effects", among = "among-individual terms",
                disp = "variance model", standardise = "standardisation")
    for (f in names(fields)) {
      vals <- vapply(model_entries, function(e) { v <- e$methods$models[[f]]; if (is.null(v)) "" else paste(v, collapse = " ") }, character(1))
      ok <- nzchar(vals)
      if (length(unique(vals[ok])) > 1) {
        conflicts <- c(conflicts, paste0("Different ", fields[[f]], ": ",
                                         paste(paste0(vapply(model_entries[ok], lab, character(1)), " (", vals[ok], ")"), collapse = "; "),
                                         ". The methods describe the first; state which is primary."))
      }
    }
  }
  vis_entries <- entries[vapply(titles, function(t) any(startsWith(t, vis_titles[1:3])), logical(1))]
  if (length(vis_entries) > 1) {
    vals <- vapply(vis_entries, function(e) paste(e$methods$visual$proxy %||% "", e$methods$visual$n_bins %||% "", e$methods$visual$bin_method %||% ""), character(1))
    if (length(unique(vals)) > 1) conflicts <- c(conflicts, "Step-2 figures use different grouping variables or bins: the methods describe the first.")
  }
  if (has("Individual-level function comparison") && !is.null(mm)) {
    tab <- pick("Individual-level function comparison")[[1]]$tables[[1]]
    lead <- if (is.data.frame(tab) && nrow(tab) && "Function" %in% names(tab)) as.character(tab$Function[[1]]) else ""
    if (nzchar(lead) && !identical(lead, mm$age_function))
      conflicts <- c(conflicts, sprintf("Step 4 favoured the %s function; the models used %s.", lead, mm$age_function))
  }
  if (has("Error-family check with") && !is.null(mm)) {
    tab <- pick("Error-family check with")[[1]]$tables[[1]]
    if (is.data.frame(tab) && nrow(tab) > 1 && all(c("Family", "AIC") %in% names(tab))) {
      tab <- tab[is.finite(tab$AIC), , drop = FALSE]
      tab <- tab[order(tab$AIC), , drop = FALSE]
      here <- family_label(mm$family)
      if (nrow(tab) > 1 && here %in% tab$Family && !identical(tab$Family[[1]], here) && tab$AIC[tab$Family == here][[1]] - tab$AIC[[1]] > 2)
        conflicts <- c(conflicts, sprintf("The error-family check favoured %s over %s (\u0394AIC > 2).", tab$Family[[1]], here))
    }
  }
  list(paragraphs = paras, conflicts = conflicts, references = unname(METHODS_REFS[unique(refs)]))
}
